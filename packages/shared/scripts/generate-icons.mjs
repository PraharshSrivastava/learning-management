// Builds src/ui/icons/iconData.ts from icon-names.txt.
// Names use the Flutter Icons.* convention: `_outlined` -> outlined, `_rounded` -> round, else filled.
// Run: pnpm --filter @lms/shared icons
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const iconsDir = join(here, '../src/ui/icons')
const require = createRequire(import.meta.url)
const svgRoot = dirname(require.resolve('@material-design-icons/svg/package.json'))

// Flutter names with no file of the same name in the classic set.
const aliases = {
  info_outline: 'outlined/info',
  info_outline_rounded: 'outlined/info',
  lightbulb_outline: 'outlined/lightbulb',
  lock_outline: 'outlined/lock',
  lock_outline_rounded: 'outlined/lock',
  play_circle_fill: 'filled/play_circle',
}
// Material Symbols only (not in the classic set). Source: google/material-design-icons
// symbols/web/edit_document/materialsymbolsoutlined/edit_document_fill1_24px.svg
const inline = {
  edit_document: {
    viewBox: '0 -960 960 960',
    body: '<path d="M240-80q-33 0-56.5-23.5T160-160v-640q0-33 23.5-56.5T240-880h320l240 240v120q-23 5-43 16t-37 28L480-237v157H240Zm320 0v-123l221-220q9-9 20-13t22-4q12 0 23 4.5t20 13.5l37 37q8 9 12.5 20t4.5 22q0 11-4 22.5T903-300L683-80H560Zm263-224 37-39-37-37-38 38 38 38ZM520-600h200L520-800l200 200-200-200v200Z"/>',
  },
}

function fileFor(name) {
  if (aliases[name]) return aliases[name]
  if (name.endsWith('_outlined')) return `outlined/${name.slice(0, -'_outlined'.length)}`
  if (name.endsWith('_rounded')) return `round/${name.slice(0, -'_rounded'.length)}`
  return `filled/${name}`
}

const names = [
  ...new Set(readFileSync(join(iconsDir, 'icon-names.txt'), 'utf8').split(/\s+/).filter(Boolean)),
].sort()
const entries = names.map((name) => {
  if (inline[name]) return [name, inline[name]]
  const svg = readFileSync(join(svgRoot, `${fileFor(name)}.svg`), 'utf8')
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1] ?? '0 0 24 24'
  const body = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
  return [name, { viewBox, body }]
})

const out = [
  '// Generated by scripts/generate-icons.mjs from icon-names.txt. Do not edit.',
  '',
  'export const iconData = {',
  ...entries.map(([name, data]) => `  ${name}: ${JSON.stringify(data)},`),
  '} as const satisfies Record<string, { viewBox: string; body: string }>',
  '',
  'export type IconName = keyof typeof iconData',
  '',
].join('\n')
writeFileSync(join(iconsDir, 'iconData.ts'), out)
console.log(`Wrote ${entries.length} icons`)
